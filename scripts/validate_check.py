#!/usr/bin/env python3
"""
UltraRig Check Report Validator

Validates UltraRig-Check JSON diagnostic reports, verifies hardware compatibility
signatures, and checks for privacy risks (accidental leaks of backup folders or .bin files).

Usage:
    python scripts/validate_check.py <path_to_report.json>
    python scripts/validate_check.py --issue <issue_number>
"""

import sys
import os
import re
import json
import argparse
import subprocess
import urllib.request


def check_for_leaks(text: str) -> list:
    """Detect accidental mentions or attachments of private backup folders or binary dumps."""
    findings = []
    patterns = [
        (r'\.bin\b', 'Direct binary (.bin) file reference detected'),
        (r'backup_\d{8}', 'Backup date folder reference detected'),
        (r'backup_[a-zA-Z0-9_-]+', 'Unit backup folder pattern detected')
    ]
    for pattern, desc in patterns:
        if re.search(pattern, text, re.IGNORECASE):
            findings.append(desc)
    return findings


def analyze_report(data: dict) -> dict:
    """Extract key compatibility and hardware metrics from an UltraRig-Check JSON object."""
    tool = data.get("tool", "UltraRig-Check")
    tool_version = data.get("tool_version", "N/A")
    date = data.get("date", "N/A")
    identify = data.get("identify_before", data.get("model", "Unknown"))
    verdict = data.get("verdict", "UNKNOWN")
    support_code = data.get("support_code", "")
    pedal_id = data.get("pedal_id", "N/A")
    platform = data.get("pc", {}).get("platform", "N/A")

    checks = data.get("checks", [])
    notable_checks = []
    for c in checks:
        cid = c.get("id")
        if cid in ["identify", "support", "flash_structure", "bootloader"]:
            notable_checks.append({
                "id": cid,
                "status": c.get("status", "INFO"),
                "detail": c.get("detail", "")
            })

    return {
        "tool": tool,
        "tool_version": tool_version,
        "date": date,
        "identify": identify,
        "verdict": verdict,
        "support_code": support_code,
        "pedal_id": pedal_id,
        "platform": platform,
        "notable_checks": notable_checks
    }


def format_markdown_summary(analysis: dict, leaks: list, source: str) -> str:
    """Format analysis into a GitHub-friendly markdown comment."""
    verdict = analysis["verdict"]
    if verdict == "READY":
        badge = "🟢 **READY (Compatible)**"
    elif "WARNING" in verdict:
        badge = "🟡 **READY WITH WARNINGS**"
    else:
        badge = f"🔴 **{verdict}**"

    lines = [
        "### 🤖 UltraRig Check Diagnostic Analysis",
        f"Analyzed data from **{source}**.\n",
        "| Parameter | Value |",
        "|---|---|",
        f"| **Verdict** | {badge} |",
        f"| **Hardware Identity** | `{analysis['identify']}` |",
        f"| **Pedal ID** | `{analysis['pedal_id']}` |",
        f"| **Tool Version** | `{analysis['tool_version']}` ({analysis['date']}) |",
        f"| **Host Environment** | `{analysis['platform']}` |",
        ""
    ]

    if leaks:
        lines.append("> ⚠️ **Privacy Warning:** Potential backup/binary files detected:")
        for leak in leaks:
            lines.append(f"> - {leak}")
        lines.append("> *Reminder: Never share `backup_<date>` or `.bin` files publicly.*\n")

    if analysis["notable_checks"]:
        lines.append("#### Key Diagnostic Check Results:")
        for c in analysis["notable_checks"]:
            lines.append(f"- **{c['id']}** ({c['status']}): {c['detail']}")
        lines.append("")

    lines.append("---")
    lines.append("*Generated by `scripts/validate_check.py`*")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Validate UltraRig-Check diagnostic reports.")
    parser.add_argument("file", nargs="?", help="Path to local UltraRig-check-*.json file")
    parser.add_argument("--issue", type=str, help="GitHub issue number to inspect and validate")
    parser.add_argument("--comment", action="store_true", help="Post comment to GitHub issue if --issue is provided")
    args = parser.parse_args()

    if not args.file and not args.issue:
        parser.print_help()
        sys.exit(1)

    raw_text = ""
    json_data = None
    source_desc = ""

    if args.issue:
        source_desc = f"GitHub Issue #{args.issue}"
        print(f"Fetching issue #{args.issue} via gh CLI...")
        try:
            issue_json = subprocess.check_output(
                ["gh", "issue", "view", args.issue, "--json", "body,title,comments"]
            ).decode("utf-8")
            issue_obj = json.loads(issue_json)
            raw_text = issue_obj.get("body", "")

            # Look for attachment URL
            attachment_match = re.search(r'https://github\.com/user-attachments/files/\S+?\.json', raw_text)
            if attachment_match:
                url = attachment_match.group(0)
                req = urllib.request.Request(url, headers={"User-Agent": "UltraRig-Validator"})
                with urllib.request.urlopen(req) as resp:
                    json_data = json.loads(resp.read().decode("utf-8"))
            else:
                # Look for embedded code block
                codeblock_match = re.search(r'```(?:json)?\s*(\{[\s\S]+?\})\s*```', raw_text)
                if codeblock_match:
                    json_data = json.loads(codeblock_match.group(1))
        except Exception as e:
            print(f"Error fetching issue data: {e}", file=sys.stderr)
            sys.exit(1)

    elif args.file:
        source_desc = os.path.basename(args.file)
        if not os.path.exists(args.file):
            print(f"Error: File not found: {args.file}", file=sys.stderr)
            sys.exit(1)
        with open(args.file, "r", encoding="utf-8") as f:
            raw_text = f.read()
        try:
            json_data = json.loads(raw_text)
        except json.JSONDecodeError as e:
            print(f"Error: Invalid JSON syntax in {args.file}: {e}", file=sys.stderr)
            sys.exit(1)

    if not json_data:
        print("No valid UltraRig-Check JSON data could be extracted.")
        sys.exit(1)

    leaks = check_for_leaks(raw_text)
    analysis = analyze_report(json_data)
    summary_md = format_markdown_summary(analysis, leaks, source_desc)

    print("\n" + "=" * 60)
    print(summary_md)
    print("=" * 60 + "\n")

    if args.issue and args.comment:
        print(f"Posting summary comment to issue #{args.issue}...")
        subprocess.run(["gh", "issue", "comment", args.issue, "--body", summary_md])


if __name__ == "__main__":
    main()
